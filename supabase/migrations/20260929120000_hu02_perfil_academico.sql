begin;

-- ---------------------------------------------------------------------
-- 1. Catálogo: divisiones y carreras
--    Viven en tablas para poder cambiar el catálogo sin tocar código.
-- ---------------------------------------------------------------------
create table if not exists public.divisiones (
  id      smallint generated by default as identity primary key,
  nombre  text not null unique,
  activo  boolean not null default true,
  orden   smallint not null default 0
);

create table if not exists public.carreras (
  id          smallint generated by default as identity primary key,
  division_id smallint not null references public.divisiones (id) on delete restrict,
  nombre      text not null,
  activo      boolean not null default true,
  orden       smallint not null default 0,
  constraint carreras_nombre_division_unq unique (division_id, nombre),
  -- Necesario para la FK compuesta de usuarios (carrera ∈ división).
  constraint carreras_id_division_unq unique (id, division_id)
);

create index if not exists carreras_division_idx on public.carreras (division_id);

alter table public.divisiones enable row level security;
alter table public.carreras   enable row level security;

drop policy if exists "Catalogo divisiones legible por autenticados" on public.divisiones;
create policy "Catalogo divisiones legible por autenticados"
  on public.divisiones for select to authenticated using (true);

drop policy if exists "Catalogo carreras legible por autenticados" on public.carreras;
create policy "Catalogo carreras legible por autenticados"
  on public.carreras for select to authenticated using (true);
-- Sin políticas de insert/update/delete: el catálogo solo se edita desde
-- el panel de Supabase (rol service_role), nunca desde la app.

-- ---------------------------------------------------------------------
-- 1.1 SEED PROVISIONAL  ⚠️  NO ES EL CATÁLOGO OFICIAL DE LA UTSJR  ⚠️
--     Sirve solo para poder probar el flujo en el Sprint 2.
