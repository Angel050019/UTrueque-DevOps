-- Requiere la migración de HU-02 (tabla public.usuarios con perfil_completo).
--
-- Flujo que sigue la app:
--   1. Sube cada foto a Storage: publicaciones/<id del usuario>/<archivo>.jpg
--   2. Hace UN solo POST /rest/v1/publicaciones con los datos y la lista de
--      rutas de las fotos → la API responde 201 Created.
